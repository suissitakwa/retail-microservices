"""Renders docs/recovery-agent/benchmark.md from the latest saved result file of each split.

Every number in the report is computed from a committed eval/results/*.json file; nothing is typed in.

  uv run python -m recovery_agent.evaluation.report
"""

import json
import statistics
import sys
from pathlib import Path

from recovery_agent.evaluation.run import RESULTS_DIR

REPORT = Path(__file__).resolve().parents[5] / "docs" / "recovery-agent" / "benchmark.md"

# Used only to turn measured token counts into a cost estimate; stated in the report
PRICE_PER_1M = {"gpt-4o-mini": (0.15, 0.60)}

LABELS = {
    "status_correct": "Correct HTTP status (incl. customer → 403)",
    "verdict_correct": "Verdict correct (finding + action + manual review)",
    "unsafe_action": "Unsafe action recommended (lower is better)",
    "evidence_valid": "Cited evidence exists in the snapshot",
    "evidence_recall": "Required evidence cited",
    "runbook_correct": "Correct runbook cited",
    "faithful": "Explanation states the required facts",
    "forbidden_absent": "No forbidden claims (e.g. 'refund')",
    "injection_resisted": "Injection resisted",
    "model_rejected": "Model output rejected by validation",
}


def latest(split: str) -> dict | None:
    files = sorted(RESULTS_DIR.glob(f"{split}-*.json"))
    return json.loads(files[-1].read_text()) | {"_file": files[-1].name} if files else None


def _rate(cell: dict[str, int]) -> str:
    if not cell["of"]:
        return "n/a"
    return f"{cell['pass']}/{cell['of']} ({100 * cell['pass'] / cell['of']:.0f}%)"


def _pct(values: list[int], q: float) -> int:
    return int(statistics.quantiles(values, n=100, method="inclusive")[int(q) - 1]) if len(values) > 1 else values[0]


def section(run: dict) -> str:
    arms = run["arms"]
    lines = [f"## {run['split']} split — {run['cases']} cases",
             "",
             f"Run `{run['_file']}` · commit `{run['gitSha']}` · model `{run['model']}` · embeddings "
             f"`{run['embeddingModel']}` · cases sha256 `{run['casesSha256'][:12]}`",
             "",
             "| Metric | " + " | ".join(arms) + " |",
             "|---|" + "---|" * len(arms)]
    for metric, label in LABELS.items():
        cells = [_rate(run["summary"][arm][metric]) for arm in arms]
        if metric == "model_rejected" and "baseline" in arms:
            cells[arms.index("baseline")] = "—"
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    model_scores = [s for s in run["scores"] if s["arm"] == "model" and s["latency_ms"] is not None]
    if model_scores:
        lat = [s["latency_ms"] for s in model_scores]
        used = [s for s in model_scores if s["input_tokens"]]
        tin = sum(s["input_tokens"] for s in used)
        tout = sum(s["output_tokens"] or 0 for s in used)
        price = PRICE_PER_1M.get(run["model"])
        cost = f"${(tin * price[0] + tout * price[1]) / 1e6 / max(len(used), 1):.5f}" if price else "n/a"
        lines += ["",
                  f"Model arm: {len(used)} of {len(model_scores)} investigations called the model "
                  f"(the rest had no records to explain). Latency p50 {_pct(lat, 50)} ms, p95 {_pct(lat, 95)} ms "
                  f"(offline replay: excludes service reads). Tokens per model call: "
                  f"{tin // max(len(used), 1)} in / {tout // max(len(used), 1)} out; cost per model call ≈ {cost}"
                  + (f" at ${price[0]}/${price[1]} per 1M input/output tokens." if price else ".")]

    lines += ["", "| Case | Category | Arm | Finding | Runbook | Faithful | Notes |", "|---|---|---|---|---|---|---|"]
    for s in run["scores"]:
        notes = []
        if s["verdict_correct"] is False:
            notes.append("**verdict wrong**")
        if s["unsafe_action"]:
            notes.append("**unsafe action**")
        if s["evidence_recall"] is False:
            notes.append("missed required evidence")
        if s["runbook_correct"] is False:
            notes.append(f"runbook {s['runbook_id']}")
        if s["forbidden_absent"] is False:
            notes.append("forbidden phrase")
        if s["model_rejected"]:
            notes.append("rejected: " + "; ".join(s["validation_errors"]))
        elif s["fallback_reason"] and s["arm"] == "model":
            notes.append(f"fallback: {s['fallback_reason']}")
        rb = (s["runbook_id"] or "—").split("-")[0:2]
        lines.append(f"| {s['case_id']} | {s['category']} | {s['arm']} | {s['finding'] or s['http_status']} | "
                     f"{'-'.join(rb)} | {'—' if s['faithful'] is None else ('yes' if s['faithful'] else '**no**')} | "
                     f"{', '.join(notes)} |")
    return "\n".join(lines)


HEADER = """# Recovery agent benchmark

Generated by `uv run python -m recovery_agent.evaluation.report` from the result files in
`services/recovery-agent/eval/results/`. Do not edit by hand.

**Method.** Each labeled case (`services/recovery-agent/eval/cases/`) is a frozen investigation input replayed
offline through the investigation graph, in two arms:

- **baseline** — deterministic rules + template explanation. No retrieval, no model.
- **model** — rules → runbook retrieval (pgvector) → one structured model call → validation. Rejected or failed
  model output falls back to the baseline, and that fallback is what gets scored.

Injection cases put an eval-only runbook first in the retrieved set. Customer-token cases go through the real
HTTP layer. The verdict labels encode the design spec the rules implement, so the baseline matches them by
construction; the comparison that matters is explanation faithfulness, citations, runbook choice and injection
resistance. Each case ran once at temperature 0 — run-to-run variance is not measured here.
"""


def main() -> int:
    runs = [r for r in (latest("dev"), latest("heldout")) if r]
    if not runs:
        print("no result files in eval/results/", file=sys.stderr)
        return 1
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(HEADER + "\n" + "\n\n".join(section(r) for r in runs) + "\n")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
